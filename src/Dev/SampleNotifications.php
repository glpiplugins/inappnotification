<?php

namespace GlpiPlugin\Inappnotification\Dev;

use CommonDBTM;
use GlpiPlugin\Inappnotification\Service\AlertStore;
use GlpiPlugin\Inappnotification\Service\ScheduledNotificationStore;

/**
 * Developer-only helpers that seed sample notifications so the bell, the muted page and the
 * "upcoming" pages can be exercised in a dev environment. Reachable only through front/dev.php,
 * which is gated by the `dev_test_panel` setting (or a development GLPI environment).
 *
 * All seeded in-app notifications carry an "[TEST] " name prefix and all seeded upcoming rows a
 * "devtest:" fingerprint prefix, so clear() removes exactly what was generated here.
 */
class SampleNotifications
{
    private const NAME_PREFIX = '[TEST] ';
    private const FP_PREFIX = 'devtest:';

    /**
     * One unread notification per source family, captured through the real notification-mode path.
     *
     * @return int number of notifications captured
     */
    public static function triggerSamples(int $users_id): int
    {
        if ($users_id <= 0) {
            return 0;
        }

        // itemtype => human label; the itemtype drives the resolved source_group / tab.
        $samples = [
            'Ticket'            => 'Ticket assigned to you',
            'SavedSearch_Alert' => 'Saved search threshold reached',
            'Project'           => 'Project deadline approaching',
            'Reminder'          => 'Reminder is due',
            'SLA'               => 'SLA escalation',
            'CronTask'          => 'Scheduled task finished',
            'Computer'          => 'Generic alert',
        ];

        $count = 0;
        $i = 0;
        foreach ($samples as $itemtype => $label) {
            // Point each sample at a real item of that type (if any exists) so the bell entry
            // deep-links to the actual source instead of falling back to the notification list.
            $captured = AlertStore::captureFromNotificationMode([
                'to'               => $users_id,
                'itemtype_trigger' => $itemtype,
                'items_id_trigger' => self::firstItemId($itemtype),
                'event'            => 'devtest_sample_' . $i,
                'subject'          => self::NAME_PREFIX . $label,
                'content_text'     => 'Sample in-app notification generated by the developer test panel.',
                '_entities_id'     => 0,
            ]);
            if ($captured) {
                $count++;
            }
            $i++;
        }

        return $count;
    }

    /**
     * Notifications in every state: unread, read, snoozed (future), suppressed and an expired
     * snooze (which the next bell poll re-notifies).
     */
    public static function triggerStates(int $users_id): void
    {
        if ($users_id <= 0) {
            return;
        }

        $now    = $_SESSION['glpi_currenttime'] ?? date('Y-m-d H:i:s');
        $future = date('Y-m-d H:i:s', strtotime($now) + 86400);
        $past   = date('Y-m-d H:i:s', strtotime($now) - 3600);

        // Deep-link the state examples to a real ticket (if any) so clicking them opens the source.
        $source = self::sampleSource('Ticket');

        self::insertAlert($users_id, array_merge($source, ['alert_name' => self::NAME_PREFIX . 'Unread example', 'is_read' => 0, 'unread_count' => 2]));
        self::insertAlert($users_id, array_merge($source, ['alert_name' => self::NAME_PREFIX . 'Read example', 'is_read' => 1, 'unread_count' => 0]));
        self::insertAlert($users_id, array_merge($source, ['alert_name' => self::NAME_PREFIX . 'Snoozed example', 'is_read' => 1, 'unread_count' => 0, 'snoozed_until' => $future]));
        self::insertAlert($users_id, array_merge($source, ['alert_name' => self::NAME_PREFIX . 'Suppressed example', 'is_read' => 1, 'unread_count' => 0, 'is_suppressed' => 1]));
        self::insertAlert($users_id, array_merge($source, ['alert_name' => self::NAME_PREFIX . 'Expired snooze (re-notifies)', 'is_read' => 1, 'unread_count' => 0, 'snoozed_until' => $past]));
    }

    /**
     * Seed the materialized global "upcoming" table with rows for: the current user, another
     * (demo) user, and an unresolved-recipient row. Makes the per-user recipient scoping visible:
     * front/scheduled.php shows only the current user's row; front/scheduled_all.php shows all.
     * The freshness timestamp is bumped so views do not immediately rebuild (and wipe) the seed;
     * the hourly cron will replace it on its next run.
     */
    public static function seedUpcoming(int $users_id): void
    {
        /** @var \DBmysql $DB */
        global $DB;

        if ($users_id <= 0 || !ScheduledNotificationStore::tableReadyGlobal()) {
            return;
        }

        $now   = $_SESSION['glpi_currenttime'] ?? date('Y-m-d H:i:s');
        $soon  = date('Y-m-d H:i:s', strtotime($now) + 3600);
        $later = date('Y-m-d H:i:s', strtotime($now) + 7200);

        self::clearSeededUpcoming();

        $self_label = trim((string) getUserName($users_id, 0, true));
        if ($self_label === '') {
            $self_label = sprintf('%s #%d', __('User'), $users_id);
        }

        self::insertUpcoming($users_id, $self_label, self::NAME_PREFIX . 'Your upcoming reminder', $soon);
        self::insertUpcoming(2147483640, __('Demo other user', 'inappnotification'), self::NAME_PREFIX . "Another user's reminder", $soon);
        self::insertUpcoming(0, __('Recipients from notification targets', 'inappnotification'), self::NAME_PREFIX . 'Unresolved-recipient item', $later);

        // Keep the global table "fresh" so ensureGlobalFresh() does not rebuild and wipe the seed.
        ScheduledNotificationStore::markGlobalFresh();
    }

    /**
     * Remove everything this panel generated (test in-app notifications + seeded upcoming rows).
     */
    public static function clear(int $users_id): void
    {
        /** @var \DBmysql $DB */
        global $DB;

        if ($users_id > 0) {
            $DB->delete(AlertStore::TABLE, [
                'users_id' => $users_id,
                ['alert_name' => ['LIKE', self::NAME_PREFIX . '%']],
            ]);
        }

        self::clearSeededUpcoming();
        // The user's projected per-user upcoming table self-heals on their next visit to the page.
    }

    /**
     * @param array<string, mixed> $overrides
     */
    private static function insertAlert(int $users_id, array $overrides): void
    {
        /** @var \DBmysql $DB */
        global $DB;

        $now = $_SESSION['glpi_currenttime'] ?? date('Y-m-d H:i:s');

        $DB->insert(AlertStore::TABLE, array_merge([
            'users_id'              => $users_id,
            'entities_id'           => 0,
            'savedsearches_id'      => 0,
            'savedsearch_alerts_id' => 0,
            'alert_name'            => self::NAME_PREFIX . 'Sample',
            'alert_message'         => 'Generated by the developer test panel.',
            'target_url'            => '',
            'source_group'          => 'other',
            'source_label'          => 'Other',
            'source_itemtype'       => '',
            'source_items_id'       => 0,
            'alert_fingerprint'     => self::FP_PREFIX . bin2hex(random_bytes(8)),
            'occurrence_count'      => 1,
            'unread_count'          => 1,
            'is_read'               => 0,
            'is_suppressed'         => 0,
            'snoozed_until'         => null,
            'last_triggered_at'     => $now,
            'date_creation'         => $now,
            'date_mod'              => $now,
        ], $overrides));
    }

    private static function insertUpcoming(int $recipient_users_id, string $recipient_label, string $item_label, string $scheduled_at): void
    {
        /** @var \DBmysql $DB */
        global $DB;

        $now = $_SESSION['glpi_currenttime'] ?? date('Y-m-d H:i:s');

        $DB->insert(ScheduledNotificationStore::GLOBAL_TABLE, [
            'recipient_users_id' => $recipient_users_id,
            'recipient_label'    => $recipient_label !== '' ? $recipient_label : (string) $recipient_users_id,
            'kind'               => 'pending_autoreminder',
            'kind_label'         => __('Automatic reminder'),
            'scheduled_at'       => $scheduled_at,
            'itemtype'           => 'Ticket',
            'items_id'           => 0,
            'item_label'         => $item_label,
            'item_url'           => '',
            'detail'             => 'Generated by the developer test panel.',
            'entities_id'        => 0,
            'entity_label'       => __('All entities'),
            'fingerprint'        => self::FP_PREFIX . bin2hex(random_bytes(8)),
            'date_creation'      => $now,
            'date_mod'           => $now,
        ]);
    }

    private static function clearSeededUpcoming(): void
    {
        /** @var \DBmysql $DB */
        global $DB;

        if (!ScheduledNotificationStore::tableReadyGlobal()) {
            return;
        }

        $DB->delete(ScheduledNotificationStore::GLOBAL_TABLE, [
            ['fingerprint' => ['LIKE', self::FP_PREFIX . '%']],
        ]);
    }

    /**
     * First existing (non-deleted) id of the given itemtype, or 0 when none exists.
     */
    private static function firstItemId(string $itemtype): int
    {
        /** @var \DBmysql $DB */
        global $DB;

        $item = getItemForItemtype($itemtype);
        if (!$item instanceof CommonDBTM) {
            return 0;
        }

        $table = $item::getTable();
        if ($table === '' || !$DB->tableExists($table)) {
            return 0;
        }

        $where = $DB->fieldExists($table, 'is_deleted') ? ['is_deleted' => 0] : [];
        $row = $DB->request([
            'SELECT' => ['id'],
            'FROM'   => $table,
            'WHERE'  => $where,
            'ORDER'  => ['id ASC'],
            'LIMIT'  => 1,
        ])->current();

        return (int) ($row['id'] ?? 0);
    }

    /**
     * Source columns (source_itemtype/source_items_id) pointing at a real item of $itemtype, so
     * the bell entry deep-links to it. Empty source when no such item exists. target_url is left
     * empty on purpose — the bell resolves it from the source fields at read time.
     *
     * @return array{source_itemtype: string, source_items_id: int, target_url: string}
     */
    private static function sampleSource(string $itemtype): array
    {
        $items_id = self::firstItemId($itemtype);
        if ($items_id <= 0) {
            return ['source_itemtype' => '', 'source_items_id' => 0, 'target_url' => ''];
        }

        return ['source_itemtype' => $itemtype, 'source_items_id' => $items_id, 'target_url' => ''];
    }
}
